test('a disconnected player retains their slot during the reconnection grace period', () => {
  const f = lobby();
  const session = f.sessions[1];
  f.service.disconnect(session.id);
  f.advance(DISCONNECT_GRACE - 1000);
  assert.ok(f.room.players.has(session.id));
  f.service.connect(session.token);
  f.advance(7000);
  assert.ok(f.room.players.has(session.id));
  f.service.disconnect(session.id);
  f.advance(DISCONNECT_GRACE + 6000);
  assert.ok(!f.room.players.has(session.id));
});

test('practice uses four explicitly labeled bots, stays private, and honors the chosen role', () => {
  const h = harness(), session = h.service.connect();
  h.service.profile(session.id, { name: 'Yago', color: 'coral' });
  const { code } = h.service.create(session.id, { role: 'impostor' }, true);
  const room = h.service.rooms.get(code);
  const snapshot = h.service.serialize(room, session.id);
  assert.equal(snapshot.players.filter(p => p.bot).length, 4);
  assert.equal(snapshot.self.role, 'impostor');
  assert.equal(snapshot.phase, 'countdown');
  assert.equal(h.service.summaries().length, 0);
  assert.equal([...room.players.values()].filter(p => p.role === 'impostor').length, 1);
  const stranger = h.service.connect();
  assert.throws(() => h.service.join(stranger.id, { code }), /não encontrada/);
});

test('reset clears old results and makes a public room joinable again', () => {
  const f = running();
  f.room.phase = 'ended';
  f.room.result = { winner: 'crewmate' };
  assert.throws(() => f.service.reset(f.sessions[1].id), /capitão/);
  f.service.reset(f.host);
  assert.equal(f.room.phase, 'lobby');
  assert.equal(f.room.result, null);
  assert.equal(f.room.map, 'lobby');
  assert.equal(f.service.summaries().length, 1);
  assert.ok([...f.room.players.values()].every(p => p.alive && p.tasks.length === 0));
});

test('shared collision geometry prevents walking through solid tiles', () => {
  assert.equal(canStand('ship', 0, 0), false);
  assert.equal(canStand('ship', 556, 149), true);
  const start = { x: 556, y: 149 };
  const step = movePosition('ship', start, { x: 1, y: 1 }, 0.1);
  assert.ok(Math.hypot(step.x - start.x, step.y - start.y) <= 10.61);
  assert.equal(hasLineOfSight('ship', start, { x: 559, y: 150 }), true);
  for (const task of TASKS) assert.ok(findPath(start, task).length > 0);
});
